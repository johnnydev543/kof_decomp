#!/usr/bin/env python3
"""mkrom.py - complete matching build of the KOF97 program ROMs from source.

  P1 (1 MB, 68000 code + data): build/disasm/p1.s, generated by `mkasm.py --symbolize`
  P2 (4 MB, banked data at 0x200000): build/disasm/p2.s = .incbin of the extracted P2 image
     (P2 is data only; it is kept as a binary blob)

Both are assembled with GNU as/ld/objcopy, converted back to MAME's byte-swapped layout
and verified against the CRCs in games/<GAME>/game.json (MAME set; default kof97).

usage: mkrom.py [--out build/disasm] [--src build/disasm/p1.s]
"""
import argparse
import os
import subprocess
import sys
import zlib

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
sys.path.insert(0, os.path.join(ROOT, 'tools'))
import game  # noqa: E402  (games/<GAME>/: per-game data)

sys.path.insert(0, os.path.join(ROOT, 'tools'))
sys.path.insert(0, os.path.join(ROOT, 'tools', 'disasm'))
import romprep  # noqa: E402
import mkasm    # noqa: E402  (binutils prefix detection)


def assemble(src, outdir, name):
    os.makedirs(outdir, exist_ok=True)
    obj, elf, binp = [os.path.join(outdir, name + ext) for ext in ('.o', '.elf', '.bin')]
    for cmd in ([mkasm.AS, '-m68000', '--register-prefix-optional', '-o', obj, src],
                [mkasm.LD, '-Ttext=0', '-e', '_start', '-o', elf, obj],
                [mkasm.OBJCOPY, '-O', 'binary', elf, binp]):
        r = subprocess.run(cmd, capture_output=True, text=True)
        if r.returncode:
            sys.exit('%s failed:\n%s' % (cmd[0], r.stderr[:2000]))
    return open(binp, 'rb').read()


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--out', default=os.path.join(ROOT, 'build/disasm'))
    ap.add_argument('--src', default=os.path.join(ROOT, 'build/disasm/p1.s'))
    args = ap.parse_args()

    p2_src = os.path.join(args.out, 'p2.s')
    with open(p2_src, 'w') as f:
        f.write('| KOF97 P2: 4 MB of banked data (0x200000 window, bank register 0x2FFFF0), kept as a blob\n'
                '\t.text\n\t.globl _start\n_start:\n\t.incbin "%s"\n' % os.path.join(ROOT, 'build/roms/p2.bin'))
    ok = True
    for name, src in (('p1', args.src), ('p2', p2_src)):
        img = assemble(src, os.path.join(args.out, 'rom'), name)
        mame = romprep.swap16(img)                       # back to MAME's 16-bit byte-swapped layout
        mname = romprep.game.CFG['roms'][name][0]
        path = os.path.join(args.out, 'rom', mname)
        open(path, 'wb').write(mame)
        crc, want = zlib.crc32(mame), romprep.KOF97[mname]
        match = crc == want
        ok &= match
        print('%-11s %8d bytes  crc %08x  expected %08x  %s' % (mname, len(mame), crc, want, 'MATCH' if match else 'DIFFERENT'))
    print('matching build: %s' % ('OK' if ok else 'FAILED'))
    return 0 if ok else 1


if __name__ == '__main__':
    sys.exit(main())
