#!/usr/bin/env python3
"""charmap.py - attribute P1 code to characters by observation (stage-3 naming).

For every character ID a mirror match is run on the interpreter (P1 and P2 teams poked to X,X,X, the
CPU plays P2, P1 mashes, both sides are knocked out in turn so wins and losses are played) with
--exec-log. An instruction executed in X's run and in no other character's run is X-specific; code
shared only by a character and its Orochi version (Iori/Orochi Iori, Leona/Orochi Leona) is attributed
to the base character. Function entries (call targets, REA functions, jump-entered addresses) whose
own address is attributed get a name chr_<name>_<addr> in games/<GAME>/symbols/chars.txt, which
mkasm.py loads after symbols.txt.

usage: charmap.py [--frames 9000] [--jobs N]
"""
import argparse
import os
import subprocess
import sys
from concurrent.futures import ThreadPoolExecutor

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, 'tools'))
import game  # noqa: E402  (games/<GAME>/game.json: RAM addresses)
P1_TEAM, P2_TEAM = game.ram('p1_team'), game.ram('p2_team')
P1_HP, P2_HP = game.ram('p1_health'), game.ram('p2_health')
OUT = os.path.join(ROOT, 'build/charmap')
CHARS = game.CFG['characters']['names']
BASE = {int(k): v for k, v in game.CFG['characters']['base'].items()}   # Orochi versions share code with the base character
PREFIX = ['900 8 coin1', '1020 6 start1', '1440 4 a', '1580 4 a', '1600 4 right', '1620 4 a', '1640 4 right',
          '1660 4 a', '1720 4 a', '1740 4 a', '1760 4 a', '1780 4 a', '1800 4 a']


def script(cid, frames):
    pk = ','.join('poke:%x=%02x' % (a, cid) for a in list(range(P1_TEAM, P1_TEAM + 3)) + list(range(P2_TEAM, P2_TEAM + 3)))
    lines = PREFIX + ['1810 800 ' + pk]
    for i, f in enumerate(range(4200, frames, 1300)):
        lines.append('%d 1 poke:%x=0000' % (f, P2_HP if i % 2 == 0 else P1_HP))   # KO P2, then P1, ...
    for f in range(3000, frames, 900):
        lines += ['%d 6 coin1' % f, '%d 6 start1' % (f + 30)]
    lines.append('mash 2700 %d %d p1' % (frames, 1000 + cid))
    return '\n'.join(lines) + '\n'


def run(cid, frames):
    d = os.path.join(OUT, CHARS[cid])
    os.makedirs(d, exist_ok=True)
    sc = os.path.join(d, 'script.txt')
    open(sc, 'w').write(script(cid, frames))
    for f in ('exec.bin', 'nv'):
        if os.path.exists(os.path.join(d, f)):
            os.remove(os.path.join(d, f))
    subprocess.run([os.path.join(ROOT, 'build/kof97'), '--interp', '--headless', '--frames', str(frames), '--script', sc,
                    '--rtc-fixed', '883612800', '--misses', '', '--nvram', os.path.join(d, 'nv'), '--quiet',
                    '--exec-log', os.path.join(d, 'exec.bin')], check=True, capture_output=True)
    em = open(os.path.join(d, 'exec.bin'), 'rb').read()[:0x10000]
    return {i * 2 for i in range(len(em) * 8) if em[i >> 3] >> (i & 7) & 1}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--frames', type=int, default=9000)
    ap.add_argument('--jobs', type=int, default=max(1, (os.cpu_count() or 2) // 2))   # never all cores: the host runs other services
    args = ap.parse_args()
    with ThreadPoolExecutor(args.jobs) as ex:
        execs = dict(zip(range(len(CHARS)), ex.map(lambda c: run(c, args.frames), range(len(CHARS)))))
    owner = {}
    allx = set().union(*execs.values())
    for a in allx:
        who = {c for c, e in execs.items() if a in e}
        base = {BASE.get(c, c) for c in who}
        if len(base) == 1 and len(who) < len(CHARS):
            owner[a] = base.pop()

    import mkasm
    p1 = open(os.path.join(ROOT, 'build/roms/p1.be'), 'rb').read()
    bios = open(os.path.join(ROOT, 'build/roms/bios.be'), 'rb').read()
    insns = mkasm.collect_insns(p1, bios)
    calls = {t for d in insns.values() for t in d.targets if d.flow in ('call', 'jump')}
    entries = (calls | mkasm.ENTRIES | mkasm.DYN_ENTRIES) & set(insns)
    manual = mkasm.load_symbols(game.symbols('curated'))
    counts = {}
    lines = ['# Generated by tools/disasm/charmap.py - do not edit (curated names go to symbols.txt).',
             '# Function entries executed only when the named character is on screen (mirror-match runs).']
    for a in sorted(entries):
        if a in owner and a not in manual:
            c = owner[a]
            counts[c] = counts.get(c, 0) + 1
            lines.append('%06x  chr_%s_%06x  | %s-specific code (observed only in %s mirror matches)'
                         % (a, CHARS[c], a, CHARS[c], CHARS[c]))
    import chrcheck
    lines, _ = chrcheck.filter_lines(lines)      # contradicted by the moves runs / inside a function
    path = game.symbols('chars')
    open(path, 'w').write('\n'.join(lines) + '\n')
    per = {c: sum(1 for a in owner if owner[a] == c) for c in range(len(CHARS))}
    print('executed instructions: %d, character-specific: %d' % (len(allx), len(owner)))
    for c in range(len(CHARS)):
        if c in BASE:
            continue
        print('  %-13s %5d instructions, %4d function entries' % (CHARS[c], per[c], counts.get(c, 0)))
    print('wrote', path)


if __name__ == '__main__':
    main()
