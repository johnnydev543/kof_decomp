#!/usr/bin/env python3
"""Generate the shift-test coverage scripts (games/<GAME>/scripts/*.txt).

Input scripts drive the same game states in the original and the shifted image. Pokes only write
work RAM (which does not move when P1 is shifted), so they are identical in both runs. RAM map used
(found with --ram-log / --watch, see AGENT.md 7.5):
  0x10a84b-0x10a84d  P1 team member IDs (written by member select; poked during order select)
  0x108238 (word)    P1 health (player struct 0x108100 + 0x138)
  0x108438 (word)    P2 / CPU health (player struct 0x108300 + 0x138)
  0x10843a (word)    P2 damage still draining from the health bar (+ 0x13a)
  0x10a83a           round timer display (BCD; poking it does not prevent TIME OVER)
  0x10a849           P1 mode: 0 ADVANCED, 1 EXTRA
Character IDs: 0-2 Japan, 3-5 Fatal Fury, 6-8 Art of Fighting, 9-11 Ikari, 12-14 Psycho Soldier,
15-17 Women (Chizuru, Mai, King), 18-20 Korea, 21-23 New Faces, 24-26 '97 Special, 27 Iori,
28 Orochi Iori, 29 Orochi Leona, 30 Orochi, 31 Shingo; Orochi Yashiro/Shermie/Chris = 21-23 with
the flag bits at 0x10a857.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, '..', '..', '..', 'tools'))
import game  # noqa: E402  (games/<GAME>/game.json: RAM addresses)

P1_TEAM, P2_TEAM = game.ram('p1_team'), game.ram('p2_team')
P1_MODE, P1_OROCHI = game.ram('p1_mode'), game.ram('p1_orochi')
P1_HP, P2_HP = game.ram('p1_health'), game.ram('p2_health')
P2_DRAIN = game.ram('p2_health_drain')

# coin, start, mode select, member select (picks Japan team), order select
PREFIX = [
    (900, 8, 'coin1'), (1020, 6, 'start1'), (1440, 4, 'a'),
    (1580, 4, 'a'), (1600, 4, 'right'), (1620, 4, 'a'), (1640, 4, 'right'), (1660, 4, 'a'),
    (1720, 4, 'a'), (1740, 4, 'a'), (1760, 4, 'a'), (1780, 4, 'a'), (1800, 4, 'a'),
]
PREFIX_EXTRA = [
    (900, 8, 'coin1'), (1020, 6, 'start1'), (1440, 4, 'a'),
    (1570, 4, 'right'), (1590, 4, 'a'), (1610, 4, 'right'), (1630, 4, 'a'), (1650, 4, 'right'), (1670, 4, 'a'),
    (1720, 4, 'a'), (1740, 4, 'a'), (1760, 4, 'a'), (1780, 4, 'a'), (1800, 4, 'a'),
]

TEAMS = {
    'japan': (0, 1, 2), 'fatalfury': (3, 4, 5), 'aof': (6, 7, 8), 'ikari': (9, 10, 11),
    'psycho': (12, 13, 14), 'women': (15, 16, 17), 'korea': (18, 19, 20), 'newfaces': (21, 22, 23),
    'special97': (24, 25, 26), 'iori_shingo': (27, 31, 15), 'orochi_iori_leona': (28, 29, 27),
    'orochi_boss': (30, 31, 28),
    'orochi_newfaces': (21, 22, 23),
}
# Orochi Yashiro/Shermie/Chris are IDs 21-23 plus the per-member flag bits at 0x10a857 (bit n = member
# n); the select grid maps cursor slots 32-34 to (21-23, flag 1). Poking IDs 32-34 directly hangs.
EXTRA_POKES = {'orochi_newfaces': 'poke:%x=07' % P1_OROCHI}


def arcade(name, team, extra, seed, frames=60000, ko_every=300):
    ev = list(PREFIX_EXTRA if extra else PREFIX)
    pk = ','.join('poke:%x=%02x' % (P1_TEAM + i, c) for i, c in enumerate(team))
    if name in EXTRA_POKES:
        pk += ',' + EXTRA_POKES[name]
    ev.append((1810, 800, pk))
    for f in range(3600, frames, ko_every):
        ev.append((f, 1, 'poke:%x=0000' % P2_HP))       # CPU loses quickly
    for f in range(3000, frames, 900):
        ev.append((f, 6, 'coin1'))                 # continue if P1 loses
        ev.append((f + 30, 6, 'start1'))
    lines = ['# arcade run: %s team %s, %s mode (generated by gen_scripts.py)' % (name, team, 'EXTRA' if extra else 'ADVANCED'),
             '# frames %d' % frames]
    lines += ['%d %d %s' % e for e in ev]
    lines.append('mash 2700 %d %d p1' % (frames, seed))
    return lines


# special and desperation-move command motions (P1 facing right); see tools/disasm/specmap.py
_MOVES = [
    ['down', 'down,right', 'right'], ['down', 'down,left', 'left'], ['right', 'down', 'down,right'],
    ['left', 'down', 'down,left'], ['left', 'down,left', 'down', 'down,right', 'right'],
    ['right', 'down,right', 'down', 'down,left', 'left'],
    ['down', 'down,right', 'right', 'down', 'down,right', 'right'], ['down', 'down,left', 'left', 'down', 'down,left', 'left'],
    ['down', 'down,right', 'right', 'down,right', 'down', 'down,left', 'left'],
    ['down', 'down,left', 'left', 'down,left', 'down', 'down,right', 'right'],
]
_CHARGES = [[(50, 'left'), (4, 'right')], [(50, 'down'), (4, 'up')]]


_CIRCLE = ['right', 'down,right', 'down', 'down,left', 'left', 'up,left', 'up', 'up,right']
# moves3: command throws and charge desperation moves (each [(frames, keys)], button on the last step)
_HCB = ['right', 'down,right', 'down', 'down,left', 'left']
_HCF = ['left', 'down,left', 'down', 'down,right', 'right']
_W = [(90, 'right')]           # walk in first: command throws only connect up close
_MOVES3 = [_W + [(4, k) for k in _HCB], _W + [(4, k) for k in _HCF], _W + [(4, k) for k in _CIRCLE],
           _W + [(4, k) for k in _CIRCLE * 2], _W + [(4, k) for k in _HCB * 2],
           [(50, 'left'), (4, 'right'), (4, 'left'), (4, 'right')],
           [(50, 'down,left'), (4, 'down,right'), (4, 'down,left'), (4, 'up,right')]]


def moves(name, team, buttons=('a', 'b'), extra=False):
    """2P versus (P2 idle, kept at full health), P1 in EXTRA mode with low health so desperation moves
    are free: every special/DM motion with every button, then P1's member is knocked out and the next
    one does the same"""
    lines = ['# moves: %s %s buttons %s - every special and desperation move command, 2P versus, idle P2'
             % (name, team, ''.join(buttons))]
    pre = ['900 8 coin1', '960 8 coin2', '1020 6 start1'] + ['%d 4 a' % f for f in range(1080, 1400, 30)] + \
          ['1400 6 start2', '1420 8 coin2', '1440 6 start2'] + ['%d 4 p2a' % f for f in range(1500, 2400, 25)]
    pk = ','.join(['poke:%x=%02x' % (P1_TEAM + i, c) for i, c in enumerate(team)] + ['poke:%x=01' % P1_MODE] +
                  ['poke:%x=01' % a for a in range(P2_TEAM, P2_TEAM + 3)])
    body = pre + ['1950 650 ' + pk]
    t = 3740
    for member in range(3):
        body.append('%d 2 poke:%x=0010' % (t, P1_HP))        # low health: desperation moves allowed
        t += 60
        for btn in buttons:                              # 2 buttons fit in one round (no time over)
            if extra:                                    # moves3/4: walk-in throws, charge DMs
                for seq in _MOVES3:
                    tt = t
                    for i, (n, k) in enumerate(seq):
                        body.append('%d %d %s' % (tt, n, k + (',' + btn if i == len(seq) - 1 else '')))
                        tt += n
                    t = tt + 100
                continue
            for seq in _MOVES:
                for i, k in enumerate(seq):
                    body.append('%d 4 %s' % (t + 4 * i, k + (',' + btn if i == len(seq) - 1 else '')))
                t += 110
            for seq in _CHARGES:
                tt = t
                for i, (n, k) in enumerate(seq):
                    body.append('%d %d %s' % (tt, n, k + (',' + btn if i == len(seq) - 1 else '')))
                    tt += n
                t += 170
        body.append('%d 1 poke:%x=0000' % (t, P1_HP))        # knock out this member; the next one comes in
        t += 900
    for f in range(3800, t, 10):
        # P2 kept at full health (desperation moves hit hard); the damage still draining from the bar is
        # cleared too: health + drain > 0x67 never happens in play and makes the bar read past its table
        body.append('%d 1 poke:%x=0067,poke:%x=0000' % (f, P2_HP, P2_DRAIN))
    lines.insert(1, '# frames %d' % (t + 300))
    return lines + body


def versus(frames=30000):
    """two players: P1 starts, P2 joins as challenger; both mash; repeated rematches"""
    lines = ['# 2P versus run (challenger), both players mash', '# frames %d' % frames,
             '900 8 coin1', '960 8 coin2', '1020 6 start1']
    for f in range(1080, 1400, 30):
        lines.append('%d 4 a' % f)
    lines += ['1400 6 start2', '1420 8 coin2', '1440 6 start2']
    for f in range(1500, 2400, 25):
        lines.append('%d 4 p2a' % f)
    for f in range(3000, frames, 2400):
        lines += ['%d 6 coin1' % f, '%d 6 coin2' % (f + 10), '%d 6 start1' % (f + 40), '%d 6 start2' % (f + 60)]
    lines.append('mash 2400 %d 23 both' % frames)
    return lines


def gameover(frames=20000):
    """single player who never continues: continue countdown, game over, ranking / name entry"""
    lines = ['# 1P loses every match, no continue: continue screen, game over, name entry', '# frames %d' % frames]
    lines += ['%d %d %s' % e for e in PREFIX]
    for f in range(3600, 12000, 240):
        lines.append('%d 1 poke:%x=0000' % (f, P1_HP))
    for f in range(12000, frames, 40):
        lines.append('%d 4 %s' % (f, 'a' if (f // 40) % 3 else 'right'))
    return lines


def testmode(frames=30000):
    """MVS BIOS test menu entered from attract mode: the game's soft-DIP pages (cartridge header
    tables), book keeping and calendar, then exit and play with the changed settings"""
    lines = ['# MVS test mode: soft DIP pages, book keeping, calendar, then play with changed DIPs',
             '# frames %d' % frames, '1300 30 test']
    f = 1500
    def key(k, gap=40):
        nonlocal f
        lines.append('%d 4 %s' % (f, k))
        f += gap
    key('down'); key('down'); key('a', 100)                        # SETTING UP THE SOFT DIP
    key('down', 60); key('a', 100)                                 # SLOT1 K.O.F.'97 page
    for page in range(2):                                          # A cycles a value, C goes back
        for item in range(8):
            key('a', 30); key('a', 30); key('down', 30)
        key('a', 120)                                              # NEXT PAGE
    key('c', 100); key('c', 100)                                   # back to the main menu
    key('down', 60); key('a', 150); key('c', 100)                  # BOOK KEEPING
    key('down', 60); key('down', 60); key('a', 150); key('c', 100) # SETTING UP THE CALENDAR
    key('down', 60); key('a', 300)                                 # EXIT -> game restarts
    start = f + 900
    lines += ['%d 8 coin1' % start, '%d 6 start1' % (start + 120)]
    for g in range(start + 300, start + 1400, 25):
        lines.append('%d 4 a' % g)
    for g in range(start + 3000, frames, 900):
        lines += ['%d 6 coin1' % g, '%d 6 start1' % (g + 30)]
    for g in range(start + 2500, frames, 300):
        lines.append('%d 1 poke:%x=0000' % (g, P2_HP))
    lines.append('mash %d %d 77 p1' % (start + 1500, frames))
    return lines


def main():
    out = {}
    seed = 101
    for i, (name, team) in enumerate(TEAMS.items()):
        out['arcade_%02d_%s' % (i, name)] = arcade(name, team, extra=i % 2 == 1, seed=seed + i)
    for name, team in TEAMS.items():
        out['moves_%s' % name] = moves(name, team, ('a', 'b'))
        out['moves2_%s' % name] = moves(name, team, ('c', 'd'))
        out['moves3_%s' % name] = moves(name, team, ('a', 'c'), extra=True)
        out['moves4_%s' % name] = moves(name, team, ('b', 'd'), extra=True)
    out['versus'] = versus()
    out['gameover'] = gameover()
    out['testmode'] = testmode()
    for name, lines in out.items():
        with open(os.path.join(HERE, name + '.txt'), 'w') as f:
            f.write('\n'.join(lines) + '\n')
    print('wrote %d scripts' % len(out))


if __name__ == '__main__':
    main()
